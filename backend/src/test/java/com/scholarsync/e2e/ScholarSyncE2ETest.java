import com.microsoft.playwright.*;
import com.microsoft.playwright.options.SelectOption;
import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

public class ScholarSyncTest {

    public static void main(String[] args) {
        // 1. Prepare PDF file (create automatically if it doesn't exist)
        ensurePdfExists();

        // 2. Start Playwright
        try (Playwright playwright = Playwright.create()) {
            // Set headless = true for running on Jenkins
            // Change to false if you want to see the browser UI locally
            Browser browser = playwright.chromium().launch(new BrowserType.LaunchOptions()
                    .setHeadless(false) // Recommended false for local debugging, true for Jenkins
                    .setSlowMo(500));   // Slow motion 0.5s to visualize operations

            Page page = browser.newPage();

            // --- Steps 1 & 2: Access Homepage ---
            System.out.println("Accessing homepage...");
            page.navigate("http://localhost:4200/");

            // --- Step 3: Click Get Started ---
            // Use CSS selector targeting class="btn-primary" containing text 'Get Started'
            page.locator("button.btn-primary:has-text('Get Started')").click();

            // --- Steps 4-8: Login ---
            System.out.println("Logging in...");
            // Wait for redirection to auth page
            page.waitForURL("**/auth");

            // Enter Email
            page.locator("input[name='email']").fill("author@scholarsync.com");
            // Enter Password
            page.locator("input[name='password']").fill("author123");
            // Click Sign In
            page.locator("button:has-text('Sign In')").click();

            // --- Step 9: Verify login and redirection ---
            System.out.println("Login successful, entering Dashboard...");
            page.waitForURL("**/paper-submission");

            // --- Steps 10-11: Click Submit Your Paper ---
            // Based on the Inspect code, there are "Submit New Paper" and "Submit Your First Paper"
            // We prioritize clicking the main one
            page.locator("button.btn-primary:has-text('Submit New Paper')").click();

            // --- Step 12: Enter Wizard ---
            System.out.println("Start filling in paper information...");

            // --- Steps 13-14: Wizard Step 1 (Select Conference) ---
            // Wait for dropdown to appear
            page.locator("select[name='conference_id']").waitFor();
            // Select Value = "1"
            page.selectOption("select[name='conference_id']", new SelectOption().setValue("1"));
            // Click Next (locate button with matsteppernext attribute)
            page.locator("button[matsteppernext]").click();

            // --- Steps 15-16: Wizard Step 2 (Paper Information) ---
            System.out.println("Filling Step 2: Paper Information...");
            // This input has no name, relying on placeholder or structure
            // Enter Title
            page.locator("input[placeholder='Enter paper title']").fill("Testing1");

            // Select Track (second select element, or based on options)
            // The selects look like siblings, using structural location
            // Find the select box containing "Select a track"
            Locator trackSelect = page.locator("select").filter(new Locator.FilterOptions().setHasText("Select a track"));
            trackSelect.selectOption(new SelectOption().setValue("1")); // Artificial Intelligence

            // Enter Abstract
            page.locator("textarea[placeholder*='abstract']").fill("Testing purpose: This is a test abstract generated by automated testing script.");

            // Click Next
            // Note: Since the page might have multiple Next buttons (hidden), click the currently visible one
            page.locator("button[matsteppernext]:visible").click();

            // --- Steps 17-18: Wizard Step 3 (Authors) ---
            System.out.println("Filling Step 3: Authors...");
            // Locate First Name (assuming it's the first required input)
            // For accuracy, use Label text for location (HTML structure is usually label followed by input)
            page.locator("label:has-text('First Name') + input").fill("Auther");
            // Alternative: Find input under form-group containing "First Name"
            page.locator(".form-group:has-text('First Name') input").fill("Auther");

            page.locator(".form-group:has-text('Last Name') input").fill("Test1");

            // Email might conflict with login, ensure it's within this Step
            page.locator(".form-group:has-text('Email') input").fill("author@scholarsync.com");

            page.locator("input[placeholder='University/Organization']").fill("Research Institute");

            // Check Corresponding Author
            page.locator(".checkbox-label input[type='checkbox']").check();

            // Click Next
            page.locator("button[matsteppernext]:visible").click();

            // --- Steps 19-20: Wizard Step 4 (Upload File) ---
            System.out.println("Filling Step 4: Upload File...");

            // The input type=file here is hidden (style="display: none")
            // Playwright can set files directly on hidden inputs
            Path pdfPath = Paths.get("src/test/resources/sample.pdf");
            page.setInputFiles("input[type='file']", pdfPath);

            // Select File Type = PDF (Assuming it is the first select on this page)
            page.selectOption("select", "PDF");

            // Version = 1
            page.locator("input[type='number']").fill("1");

            // Click Next
            page.locator("button[matsteppernext]:visible").click();

            // --- Step 21: Wizard Step 5 (Keywords) ---
            System.out.println("Filling Step 5: Keywords...");

            // Enter manual keyword
            page.locator("input[placeholder='Type and press Enter']").fill("Keywords");
            // Click Add
            page.locator("button.btn-primary:has-text('Add')").click();

            // Click Suggested Keywords
            // Using text=... might match previously selected ones, so we look for exact class match
            page.locator(".keyword-chip:text-is(' Artificial Intelligence ')").click();
            page.locator(".keyword-chip:text-is(' Deep Learning ')").click();
            page.locator(".keyword-chip:text-is(' IoT ')").click();

            // --- Final Submission ---
            System.out.println("Submitting paper...");
            page.locator("button.btn-primary:has-text('Submit Paper')").click();

            System.out.println("Test completed!");

            // Pause for 3 seconds to let you see the result
            Thread.sleep(3000);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    // --- Helper Method: Automatically create PDF file ---
    private static void ensurePdfExists() {
        try {
            Path dirPath = Paths.get("src/test/resources");
            if (!Files.exists(dirPath)) {
                Files.createDirectories(dirPath);
            }
            File pdfFile = new File("src/test/resources/sample.pdf");
            if (!pdfFile.exists()) {
                System.out.println("Creating test PDF file...");
                boolean created = pdfFile.createNewFile();
                // Write some dummy data as placeholder
                Files.writeString(pdfFile.toPath(), "This is a dummy PDF content for testing.");
            }
        } catch (IOException e) {
            System.err.println("Failed to create PDF: " + e.getMessage());
        }
    }
}